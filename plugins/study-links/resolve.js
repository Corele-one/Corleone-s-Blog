import path from "node:path"
import { slugifyFilePath } from "@quartz-community/utils"

// The upstream shortest resolver treats ../ as a vault-root path, and cannot
// disambiguate a note from a folder with the same name. Resolve those cases
// while the link is still relative to its original note; never change sources.
export function resolveStudyLink(source, target, slugs) {
  if (!target || /^(?:[a-z][a-z\d+.-]*:|#|\/\/)/i.test(target)) return target
  const split = target.search(/[?#]/)
  const raw = split < 0 ? target : target.slice(0, split)
  const suffix = split < 0 ? "" : target.slice(split)
  let decoded
  try {
    decoded = decodeURI(raw)
  } catch {
    return target
  }
  const folder = decoded.endsWith("/")
  const slug = slugifyFilePath(decoded).replace(/\/$/, "")
  const local = path.posix.normalize(path.posix.join(path.posix.dirname(source), slug))
  const absolute = slug.replace(/^\//, "")
  const find = (candidate) => {
    candidate = slugifyFilePath(candidate)
    const exact = (name) =>
      slugs.has(name)
        ? name
        : [...slugs].find((known) => known.toLowerCase() === name.toLowerCase())
    const file = !folder && exact(candidate)
    if (file) return file
    const index = exact(candidate + "/index")
    if (index) return index
    return undefined
  }
  const explicitRelative = decoded.startsWith("./") || decoded.startsWith("../")
  let resolved
  if (explicitRelative) {
    resolved = find(local)
    // Hashtags are generated by ObsidianFlavoredMarkdown before tag pages exist.
    if (!resolved && local.startsWith("tags/")) resolved = local
  } else if (decoded.startsWith("/") || decoded.includes("/")) {
    resolved = find(absolute) ?? find(local)
  } else {
    resolved = find(local) ?? find(absolute)
    if (!resolved) {
      const matches = [...slugs].filter(
        (candidate) =>
          candidate.toLowerCase().endsWith("/" + slug.toLowerCase()) ||
          candidate.toLowerCase().endsWith("/" + slug.toLowerCase() + "/index"),
      )
      if (matches.length === 1) resolved = matches[0]
    }
  }
  return resolved ? "/" + resolved + suffix : target
}
